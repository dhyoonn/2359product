export function buildLogicFirstContent(userMessage: string, fileTexts: string[]): string {
  const filesSection = fileTexts.length > 0
    ? `\n\n[첨부 파일]\n${fileTexts.join('\n\n')}`
    : ''
  return `[기획 요청]
${userMessage || '첨부 파일을 바탕으로 마케팅 로직을 발굴해주세요.'}${filesSection}

---

[중요 지시사항 — 반드시 읽고 수행할 것]

사용자가 "방식" 또는 "전략"을 예시로 제시했더라도, 그것은 참고용 힌트일 뿐이다.
직접 STEP 1부터 수행하여 새로운 로직을 발굴해야 한다. 절대 사용자의 예시를 그대로 가져다 쓰지 말 것.

**핵심:** 하나의 전략 방식은 여러 경쟁 제품/카테고리에 각각 적용할 수 있다.
각각의 적용이 독립된 마케팅 로직(A, B, C, D...)이 된다.

예시: "대안 차단" 방식을 미백 앰플에 적용한다면
→ 로직 A: TOP 경쟁 = 비타민C 크림 (표피층만 닿음)
→ 로직 B: TOP 경쟁 = 먹는 비타민C (피부 도달률 낮음)
→ 로직 C: TOP 경쟁 = 레이저 시술 (비용·자극·다운타임)
→ 로직 D: TOP 경쟁 = 기능성 화장품 (농도 규제로 실효성 낮음)
→ 각 로직마다 "그래서 우리 제품만이 해결한다"는 독립된 설득 구조

수행 순서:
1. STEP 1: 타겟 제품 카테고리의 원료·성분·메커니즘을 분석하고 논문·연구 근거를 인용하라.
2. 기획 방식(힌트)을 기반으로 경쟁 카테고리를 3~6개 도출하고, 각각에 전략을 적용하여 독립 로직을 만들어라.
3. STEP 2(체크리스트) → STEP 3(각 로직 상세 설계) 순서로 완전히 수행하라.
4. 각 로직마다 타겟·인과구조·대안차단·①~⑤설득흐름·비유·공포소구·경쟁차별점표를 전부 작성하라.
5. 결과를 HTML로 출력하라.`
}

export function buildLogicFollowUp(userMessage: string, currentHtml: string): string {
  return `[현재 로직 발굴 결과]
${currentHtml}

[수정/추가 요청]
${userMessage}

요청에 맞게 수정하고 전체 HTML을 반환해주세요.`
}

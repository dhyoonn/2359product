export function buildProductSpecPrompt(specContent: string): string {
  return `당신은 화장품 제품 사양서 작성 전문가입니다.
아래 최종 SPEC 내용을 분석하여 제품 사양서 기획팀 섹션에 기입할 내용을 JSON으로 작성해주세요.

작성 원칙:
1. SPEC 내용에 명시된 정보만 작성하고, 없는 정보는 빈 문자열("")로 남기세요.
2. 추론이나 임의 작성은 하지 마세요.
3. 모든 내용은 한국어로 작성하세요.
4. 반드시 아래 JSON 형식으로만 응답하세요. JSON 외 다른 텍스트는 절대 포함하지 마세요.

[최종 SPEC 내용]
${specContent}

[응답 형식]
{
  "제품명": "",
  "제품유형": "",
  "유통기한": "",
  "제조사": "",
  "제품특징": ""
}`
}

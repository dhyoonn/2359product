import { type ProductType, getAllFieldKeys, getFieldConstraintsForPrompt, PRODUCT_TYPE_LABELS } from '@/lib/dev-request-fields'

export function buildDevRequestPrompt(productType: ProductType, planningContent: string): string {
  const typeLabel = PRODUCT_TYPE_LABELS[productType]
  const keys = getAllFieldKeys(productType)
  const emptyJson = Object.fromEntries(keys.map((k) => [k, '']))
  const constraints = getFieldConstraintsForPrompt(productType)

  return `당신은 커머스 기업 상품기획팀의 문서 작성 전문가입니다.
아래 상품 기획안을 분석하여 ${typeLabel} 제품 개발의뢰서를 JSON 형식으로 작성해주세요.

작성 원칙:
1. 기획안에 명시된 내용은 그대로 반영하세요.
2. 기획안에서 합리적으로 유추할 수 있는 내용은 추론하여 작성하세요.
3. 발주 수량, 희망 견적가처럼 내부 사업 결정이 필요한 항목은 빈 문자열("")로 남기세요.
4. 담당자명, 담당자 연락처는 빈 문자열("")로 남기세요.
5. 유통국가_메인, 유통국가_서브, 유통국가_채널은 빈 문자열("")로 남기세요. (기본값이 자동 적용됩니다.)
6. 타겟_성별_연령: 기획안에 구체적인 타겟 정보가 없으면 "전 연령, 남녀 공통"으로 작성하세요.
7. 기능성_메인_원료, 부원료 (식품·건기식에만 해당): 원료명과 함량만 기입하세요. 효능, 설명 등 세부 사항은 생략하세요. (예: "히알루론산 100mg, 콜라겐 50mg")
   필수_성분, 요청_성분 (화장품에만 해당): 기획안에 언급된 성분명을 그대로 나열하세요. 함량 정보가 없어도 성분명만 있으면 기입하세요. (예: "히알루론산, 나이아신아마이드, 판테놀")
8. 개발_요구사항, 기타_사항은 항상 빈 문자열("")로 남기세요.
9. 제품_컨셉: 제조사 전달용 문서이므로 상세 설명 없이 어떤 제품인지만 간략하게 작성하세요. (예: "위 건강 다이어트", "모공 케어 스킨케어", "저자극 민감성 크림" 수준으로 한 줄 이내)
10. 참고_타겟1, 참고_타겟2: 기획안에 타겟 제품 링크(URL)가 명시된 경우에만 해당 링크를 기입하세요. 링크가 없으면 빈 문자열("")로 남기세요.
11. 수분감, 유분감, 자극감, 점도 (화장품에만 해당): 기획안의 제형·컨셉·타겟 정보를 바탕으로 1~5 중 적절한 값을 제안하세요.
    - 수분감: 수분 공급이 강조된 제품일수록 높은 값 (예: 보습 크림 → 4~5, 선크림 → 2~3)
    - 유분감: 오일리한 제형일수록 높은 값 (예: 드라이 오일 → 4, 수분 젤 → 1~2)
    - 자극감: 민감성·저자극 강조 제품은 낮은 값, 필링·각질 제거는 높은 값 (예: 민감성 → 1~2, 필링 → 4~5)
    - 점도: 묽은 세럼·토너는 낮은 값, 크림·밤은 높은 값 (예: 토너 → 1~2, 크림 → 3~4, 밤 → 5)
12. 오늘 날짜(의뢰일): ${new Date().toISOString().split('T')[0]}
13. 모든 내용은 한국어로 작성하세요.
14. 반드시 아래 JSON 형식으로만 응답하세요. JSON 외 다른 텍스트는 절대 포함하지 마세요.

[기획안 섹션 → 개발의뢰서 필드 매핑 규칙]
기획안이 아래 섹션 구조(상품제안서 양식)로 작성된 경우, 각 섹션을 다음 필드에 반영하세요:
- "기획 의도" 또는 "제품 한 줄 요약" → 제품_컨셉
- "메인 소구점(USP=Identity) 및 성분" 섹션에서 성분명·원료명 부분만 추출 → 필수_성분 (소구점 설명 제외, 성분명만)
- "서브 소구점 및 성분" 섹션에서 성분명·원료명 부분만 추출 → 요청_성분 (소구점 설명 제외, 성분명만)
- "관능 및 제형 특성" 또는 "제형", "텍스처" → 제형
- "주요 타겟 전략" 또는 "타겟", "고객" → 타겟_성별_연령
- 타겟 제품 분석에 포함된 경쟁 제품 URL → 참고_타겟1, 참고_타겟2

[선택 옵션이 지정된 필드 — 반드시 아래 옵션 값만 사용하세요]
${constraints}

[기획안 내용]
${planningContent}

[응답 형식]
${JSON.stringify(emptyJson, null, 2)}`
}
